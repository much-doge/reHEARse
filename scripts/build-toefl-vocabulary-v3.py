POS_FRAMES = {'Noun': NOUN_FRAMES, 'Verb': VERB_FRAMES, 'Adjective': ADJECTIVE_FRAMES, 'Adverb': ADVERB_FRAMES}

def find_word(sentence, word):
    match = re.search(r'(?<![\w])' + re.escape(word) + r'(?![\w])', sentence, re.I)
    if not match:
        raise ValueError(f'No exact headword occurrence: {word!r} in {sentence!r}')
    start = len(sentence[:match.start()].encode('utf-16-le')) // 2
    end = len(sentence[:match.end()].encode('utf-16-le')) // 2
    return start, end - start

def example(word, pos, card_index):
    frame = SPECIAL.get((word.casefold(), pos))
    if frame is None:
        frames = POS_FRAMES[pos]
        frame = frames[(card_index * 7 + len(word)) % len(frames)]
    sentence = frame.format(w=word)
    start, length = find_word(sentence, word)
    return {'sentence': sentence, 'highlightStart': start, 'highlightLength': length, 'source': 'rehearse-authored'}

def main():
    package = json.loads(SOURCE.read_text(encoding='utf-8'))
    if len(package['cards']) != 2844:
        raise SystemExit(f"Expected 2,844 stable cards, got {len(package['cards'])}")
    for i, card in enumerate(package['cards']):
        card['example'] = example(card['headword'], card['partsOfSpeech'][0], i)
    package['contractVersion'] = 'toefl-vocabulary-package.v3'
    package['version'] = 3
    package['prompt'] = 'Which parts of speech can this word play in the reviewed vocabulary set? Select each role that fits.'
    package['sourceNote'] = 'Original contextual example sentences composed for this learning deck. The reviewed vocabulary set supplies the headwords and part-of-speech answers.'
    TARGET.write_text(json.dumps(package, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f'Wrote {len(package["cards"])} original contextual examples to {TARGET}')

if __name__ == '__main__':
    main()
